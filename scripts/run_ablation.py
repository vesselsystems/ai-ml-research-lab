"""Two follow-up analyses on the same split as run_experiment.py; writes reports/ablation.md.

Hypotheses were written here before this script was first run (2026-11-16):

H1 (model comparison). The README compared two separate ROC-AUC intervals and called the
    models indistinguishable because the intervals overlap. That is the wrong test for
    two models scored on the same rows. Prediction: the paired bootstrap interval for
    AUC(logistic) - AUC(forest) contains 0, so the conclusion stands, now for the right
    reason.

H2 (calibration). Logistic regression's poor calibration (ECE 0.150 against 0.086 for
    the forest) is caused by class_weight="balanced", which reweights the loss and inflates
    predicted probabilities. It is not caused by the model family. Prediction: an
    unweighted logistic regression keeps ROC-AUC within 0.005, because ranking is largely
    unaffected, and cuts ECE to below the forest's.

Either outcome is reported. Nothing here changes the main experiment's models or numbers.
"""

from __future__ import annotations

import platform
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
from sklearn.base import clone

from ai_ml_research_lab.data import load_dataset
from ai_ml_research_lab.experiment import (
    REPORTING_THRESHOLD,
    _holdout_split,
    build_pipelines,
    calibration_analysis,
    paired_bootstrap_auc_difference,
)
from ai_ml_research_lab.provenance import validate_provenance

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "raw" / "telco_churn.csv"
REPORT = ROOT / "reports" / "ablation.md"


def _summary(name: str, y_test: pd.Series, scores: np.ndarray) -> dict[str, object]:
    from sklearn.metrics import average_precision_score, roc_auc_score

    calibration = calibration_analysis(y_test, scores)
    predicted_positive = float(np.mean(scores >= REPORTING_THRESHOLD))
    return {
        "model": name,
        "roc_auc": roc_auc_score(y_test, scores),
        "average_precision": average_precision_score(y_test, scores),
        "brier": float(calibration["brier_score"].iloc[0]),
        "ece": float(calibration["expected_calibration_error"].iloc[0]),
        "mean_score": float(np.mean(scores)),
        "flagged_at_0_5": predicted_positive,
    }


def main() -> int:
    if not SOURCE.exists():
        raise SystemExit("Missing data/raw/telco_churn.csv; run scripts/download_data.py first.")
    check = validate_provenance(
        ROOT / "data" / "provenance.json", raw_path=SOURCE, project_root=ROOT
    )
    if not check.measurements_match:
        raise SystemExit("Refusing to analyze a snapshot that does not match data/provenance.json")

    frame = load_dataset(SOURCE)
    x_train, x_test, y_train, y_test = _holdout_split(frame, test_size=0.2, random_state=42)
    pipelines = build_pipelines(x_train)
    unweighted = clone(pipelines["logistic_regression"]).set_params(model__class_weight=None)
    models = {
        "logistic_regression (balanced, as in main run)": pipelines["logistic_regression"],
        "logistic_regression (unweighted)": unweighted,
        "random_forest (as in main run)": pipelines["random_forest"],
    }
    scores = {}
    for name, model in models.items():
        model.fit(x_train, y_train)
        scores[name] = model.predict_proba(x_test)[:, 1]
    names = list(models)
    rows = [_summary(name, y_test, scores[name]) for name in names]

    h1 = paired_bootstrap_auc_difference(y_test, scores[names[0]], scores[names[2]])
    h2 = paired_bootstrap_auc_difference(y_test, scores[names[1]], scores[names[0]])
    base_rate = float(y_test.mean())

    def fmt(value: float) -> str:
        return f"{value:.4f}"

    lines = [
        "# Ablation: paired model comparison and the calibration hypothesis",
        "",
        "Generated by `python scripts/run_ablation.py`. Same data snapshot, seed 42, and",
        "stratified 80/20 split as the main experiment.",
        f"Holdout n = {len(y_test)}, positive rate {base_rate:.4f}.",
        "The hypotheses were written in the script's docstring before the first run.",
        "",
        "| Model | ROC-AUC | Avg precision | Brier | ECE | Mean score | Flagged at 0.5 |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        lines.append(
            f"| {row['model']} | {fmt(row['roc_auc'])} | {fmt(row['average_precision'])} | "
            f"{fmt(row['brier'])} | {fmt(row['ece'])} | {fmt(row['mean_score'])} | "
            f"{fmt(row['flagged_at_0_5'])} |"
        )
    lines += [
        "",
        "Paired bootstrap of the ROC-AUC difference (1,000 row resamples, seed 42):",
        "",
        "| Comparison | Difference | 95% interval | Share of resamples where first is higher |",
        "| --- | ---: | ---: | ---: |",
        f"| H1: logistic (balanced) - forest | {fmt(h1['difference'])} | "
        f"{fmt(h1['ci_low'])} to {fmt(h1['ci_high'])} | {h1['share_first_higher']:.3f} |",
        f"| H2: logistic (unweighted) - logistic (balanced) | {fmt(h2['difference'])} | "
        f"{fmt(h2['ci_low'])} to {fmt(h2['ci_high'])} | {h2['share_first_higher']:.3f} |",
        "",
        "## Reading the result",
        "",
    ]
    h1_contains_zero = h1["ci_low"] <= 0 <= h1["ci_high"]
    lines.append(
        "- **H1:** the paired interval "
        + ("contains 0" if h1_contains_zero else "excludes 0")
        + ", so "
        + (
            "the two models are not distinguishable on ROC-AUC with this holdout."
            if h1_contains_zero
            else "this holdout does distinguish the models on ROC-AUC."
        )
        + " The prediction was that it contains 0: "
        + ("confirmed." if h1_contains_zero else "not confirmed.")
    )
    auc_shift = abs(rows[1]["roc_auc"] - rows[0]["roc_auc"])
    ece_below_forest = rows[1]["ece"] < rows[2]["ece"]
    confirmed = auc_shift <= 0.005 and ece_below_forest
    lines.append(
        f"- **H2:** removing class weights changed ROC-AUC by {auc_shift:.4f} and ECE from "
        f"{rows[0]['ece']:.4f} to {rows[1]['ece']:.4f} (forest {rows[2]['ece']:.4f}); the "
        f"mean predicted probability moved from {rows[0]['mean_score']:.3f} to "
        f"{rows[1]['mean_score']:.3f} against a base rate of {base_rate:.3f}. Prediction "
        + ("confirmed." if confirmed else "not confirmed.")
    )
    lines += [
        "",
        "Caveats: one split, one seed, and a holdout that also produced the main results. The",
        "unweighted model flags fewer customers at 0.5, so its precision and recall differ;",
        "the choice between them is a threshold and cost decision, not a calibration result.",
        "",
        "Environment: Python "
        f"{platform.python_version()}, scikit-learn {sklearn.__version__}, pandas "
        f"{pd.__version__}, numpy {np.__version__}.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
